# =============================================================================
# G1 RL 训练参数配置文件
# =============================================================================
# 所有用户可调的参数都在这里，按功能（train/play）划分。
# 修改后直接生效，不需要设环境变量，不需要改 CLI 参数。
#
# 使用方式（在容器内）：
#   from g1_config import G1_CONFIG
#   num_envs = G1_CONFIG.train.num_envs
# =============================================================================


class TrainConfig:
    """训练 (train / train-gui / resume) 参数"""

    # ── 任务名称 ───────────────────────────────────────────────────────
    task = "Unitree-G1-29dof-Velocity"

    # ── 并行环境数 ──────────────────────────────────────────────────────
    # 每个环境里有一个机器人，越大训练越快但显存消耗越多
    # 16GB 显存推荐 4096，14GB 内存推荐不超过 4096
    num_envs = 4096

    # ── 训练迭代次数 ────────────────────────────────────────────────────
    # 一个 iteration = 24 步 × num_envs 个环境
    max_iterations = 50000

    # ── 随机种子 ────────────────────────────────────────────────────────
    # -1 表示每次启动随机生成
    seed = 43


class PlayConfig:
    """回放 (play) 参数"""

    # ── 任务名称 ───────────────────────────────────────────────────────
    task = "Unitree-G1-29dof-Velocity"

    # ── 并行环境数 ──────────────────────────────────────────────────────
    # 回放时通常用较少环境，方便观察机器人行为
    num_envs = 8


class G1Config:
    """G1 训练总配置 — 按功能分组"""
    train = TrainConfig()
    play = PlayConfig()


# 全局单例，导入即用
G1_CONFIG = G1Config()
